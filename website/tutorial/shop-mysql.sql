SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS reviews, payments, order_items, orders, products, customers;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE customers (
  id INT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(160) NOT NULL UNIQUE,
  country VARCHAR(60),
  plan VARCHAR(20) COMMENT 'Subscription plan: Free, Pro, Team or Enterprise',
  signed_up_at DATE,
  lifetime_value DECIMAL(10,2) NOT NULL DEFAULT 0 COMMENT 'Total of paid orders, in USD'
) COMMENT = 'People and companies who buy from the shop';

CREATE TABLE products (
  id INT PRIMARY KEY,
  sku VARCHAR(20) NOT NULL UNIQUE,
  title VARCHAR(120) NOT NULL,
  category VARCHAR(40),
  unit_price DECIMAL(10,2) NOT NULL COMMENT 'List price in USD',
  in_stock INT NOT NULL DEFAULT 0
) COMMENT = 'Items for sale';

CREATE TABLE orders (
  id INT PRIMARY KEY,
  customer_id INT NOT NULL,
  status VARCHAR(20) NOT NULL COMMENT 'paid, refunded or pending',
  channel VARCHAR(20) COMMENT 'web, mobile or marketplace',
  currency CHAR(3) NOT NULL DEFAULT 'USD',
  total_amount DECIMAL(10,2) NOT NULL,
  created_at DATETIME NOT NULL,
  CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES customers(id)
) COMMENT = 'One row per checkout';

CREATE TABLE order_items (
  id INT AUTO_INCREMENT PRIMARY KEY,
  order_id INT NOT NULL,
  product_id INT NOT NULL,
  quantity INT NOT NULL,
  unit_price DECIMAL(10,2) NOT NULL COMMENT 'Price paid per unit, in USD',
  CONSTRAINT fk_items_order FOREIGN KEY (order_id) REFERENCES orders(id),
  CONSTRAINT fk_items_product FOREIGN KEY (product_id) REFERENCES products(id)
) COMMENT = 'Products within each order';

CREATE TABLE payments (
  id INT AUTO_INCREMENT PRIMARY KEY,
  order_id INT NOT NULL,
  method VARCHAR(20) COMMENT 'card, paypal or bank transfer',
  amount DECIMAL(10,2) NOT NULL,
  paid_at DATETIME NOT NULL,
  CONSTRAINT fk_payments_order FOREIGN KEY (order_id) REFERENCES orders(id)
);

CREATE TABLE reviews (
  id INT AUTO_INCREMENT PRIMARY KEY,
  product_id INT NOT NULL,
  customer_id INT NOT NULL,
  rating TINYINT NOT NULL COMMENT '1 to 5 stars',
  body VARCHAR(500),
  created_at DATE NOT NULL,
  CONSTRAINT fk_reviews_product FOREIGN KEY (product_id) REFERENCES products(id),
  CONSTRAINT fk_reviews_customer FOREIGN KEY (customer_id) REFERENCES customers(id)
);

